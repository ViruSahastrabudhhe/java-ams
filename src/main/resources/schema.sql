CREATE TABLE users (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL           VARCHAR(50) NOT NULL UNIQUE,
    USERNAME        VARCHAR(50) NOT NULL,
    PASSWORD        VARCHAR(500) NOT NULL,
    CREATED_AT    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT    TIMESTAMP
);

CREATE TABLE roles (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR(50) NOT NULL
);

CREATE TABLE user_roles (
    USER_ID     BIGINT references users(id),
    ROLE_ID     BIGINT references roles(id)
);

CREATE TABLE permissions (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR NOT NULL
);

CREATE TABLE roles_permissions (
    ROLE_ID         BIGINT references roles(id),
    PERMISSION_ID    BIGINT references permissions(id)
);

CREATE TABLE TENANT_PROFILES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR NOT NULL,
    MIDDLE_NAME     VARCHAR,
    LAST_NAME       VARCHAR NOT NULL,
    USER_ID         BIGINT references users(id) UNIQUE,
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT    TIMESTAMP
);

CREATE TABLE ADDRESSES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COUNTRY VARCHAR(255) NOT NULL,
    ADDRESS_LINE VARCHAR(255) NOT NULL,
    CITY VARCHAR(255) NOT NULL,
    PROVINCE VARCHAR(255) NOT NULL,
    ZIP_CODE VARCHAR(20) NOT NULL,
    STREET VARCHAR(255) NOT NULL,
    ADDRESS_TYPE ENUM ('HOME', 'BILLING', 'BUSINESS', 'SHIPPING') DEFAULT 'HOME',
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT    TIMESTAMP
);

CREATE TABLE LANDLORD_PROFILES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR NOT NULL,
    MIDDLE_NAME     VARCHAR,
    LAST_NAME       VARCHAR NOT NULL,
    USER_ID         BIGINT references users(id),
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TABLE invoices (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER      INT NOT NULL,
    INVOICE_TOTAL       NUMBER NOT NULL DEFAULT 0.0,
    INVOICE_STATUS      ENUM ('DRAFT', 'SENT', 'PAID', 'PARTIALLY PAID', 'OVERDUE', 'VOID') DEFAULT 'DRAFT',
    DUE_DATE            DATE NOT NULL,
    USER_ID             BIGINT references users(id),
    TENANT_PROFILE_ID   BIGINT references TENANT_PROFILES(id),
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT          TIMESTAMP
);

CREATE TABLE invoice_lines (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_ID      BIGINT references invoices(id),
    ITEM_NAME       VARCHAR NOT NULL,
    DESCRIPTION     CHARACTER LARGE OBJECT,
    QUANTITY        INT NOT NULL DEFAULT 0,
    UNIT_PRICE      NUMBER NOT NULL DEFAULT 0.0,
    TOTAL_PRICE     NUMBER NOT NULL DEFAULT 0.0,
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TABLE payments (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AMOUNT_PAID         NUMBER NOT NULL DEFAULT 0.0,
    AMOUNT_CHANGE       NUMBER DEFAULT 0.0,
    PAYMENT_TYPE        ENUM ('CASH', 'CARD', 'E_WALLET') NOT NULL,
    INVOICE_ID          BIGINT references invoices(id),
    USER_ID             BIGINT references users(id),
    TENANT_PROFILE_ID   BIGINT references TENANT_PROFILES(id),
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DELETED_AT          TIMESTAMP
);

CREATE TABLE properties (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landlord_profile_id BIGINT references LANDLORD_PROFILES(id),
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP,
    DELETED_AT          TIMESTAMP
);

CREATE TABLE property_details (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id         BIGINT references properties(id),
    name                VARCHAR NOT NULL,
    property_type       VARCHAR NOT NULL,
    property_value      DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    billing_type        ENUM ('DAILY', 'MONTHLY', 'YEARLY') NOT NULL DEFAULT 'MONTHLY',
    bedroom_quantity    INT,
    bathroom_quantity   INT,
    size                VARCHAR,
    description         TEXT,
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP,
    DELETED_AT          TIMESTAMP
);

CREATE TABLE leases (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id         BIGINT references properties(id),
    tenant_profile_id   BIGINT references tenant_profiles(id),
    start_date          DATE NOT NULL,
    end_date            DATE NOT NULL,
    rent                DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    deposit             DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    billing_type        ENUM ('DAILY', 'MONTHLY', 'YEARLY') NOT NULL DEFAULT 'MONTHLY',
    status              ENUM ('DRAFT', 'TENANTS_SIGNING', 'READY_TO_SIGN', 'FINALIZED', 'EXPIRED') NOT NULL DEFAULT 'DRAFT',
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP,
    DELETED_AT          TIMESTAMP
);
