CREATE TABLE users (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL         VARCHAR(50) NOT NULL UNIQUE,
    USERNAME      VARCHAR(50) NOT NULL,
    PASSWORD      VARCHAR(500) NOT NULL,
    CREATED_AT    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    TIMESTAMP,
    DELETED_AT    TIMESTAMP
);

CREATE TABLE roles (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR(50) NOT NULL
);

CREATE TABLE user_roles (
    USER_ID     BIGINT references users(id),
    ROLE_ID     BIGINT references roles(id)
);

CREATE TABLE permissions (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR NOT NULL
);

CREATE TABLE roles_permissions (
    ROLE_ID          BIGINT references roles(id),
    PERMISSION_ID    BIGINT references permissions(id)
);

CREATE TABLE TENANT_PROFILES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR NOT NULL,
    MIDDLE_NAME     VARCHAR,
    LAST_NAME       VARCHAR NOT NULL,
    USER_ID         BIGINT references users(id) UNIQUE,
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TYPE address_type AS ENUM ('HOME', 'BILLING', 'BUSINESS', 'SHIPPING');

CREATE TABLE ADDRESSES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COUNTRY         VARCHAR(255) NOT NULL,
    ADDRESS_LINE    VARCHAR(255) NOT NULL,
    CITY            VARCHAR(255) NOT NULL,
    PROVINCE        VARCHAR(255) NOT NULL,
    ZIP_CODE        VARCHAR(20) NOT NULL,
    STREET          VARCHAR(255) NOT NULL,
    ADDRESS_TYPE    address_type DEFAULT 'HOME',
    USER_ID         BIGINT references users(id),
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TABLE LANDLORD_PROFILES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR NOT NULL,
    MIDDLE_NAME     VARCHAR,
    LAST_NAME       VARCHAR NOT NULL,
    USER_ID         BIGINT references users(id),
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TYPE invoice_status AS ENUM ('CREATED', 'PAID', 'LATE');

CREATE TABLE invoices (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER      INT NOT NULL,
    INVOICE_TOTAL       DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    INVOICE_STATUS      invoice_status DEFAULT 'CREATED',
    DUE_DATE            DATE NOT NULL,
    USER_ID             BIGINT references users(id),
    TENANT_PROFILE_ID   BIGINT references TENANT_PROFILES(id),
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP,
    DELETED_AT          TIMESTAMP
);

CREATE TABLE invoice_lines (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_ID      BIGINT references invoices(id),
    ITEM_NAME       VARCHAR NOT NULL,
    DESCRIPTION     TEXT,
    QUANTITY        INT NOT NULL DEFAULT 0,
    UNIT_PRICE      DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    TOTAL_PRICE     DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    CREATED_AT      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP,
    DELETED_AT      TIMESTAMP
);

CREATE TYPE payment_type AS ENUM ('CASH', 'CARD', 'E_WALLET');

CREATE TABLE payments (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AMOUNT_PAID         DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    AMOUNT_CHANGE       DOUBLE PRECISION DEFAULT 0.0,
    PAYMENT_TYPE        payment_type NOT NULL,
    INVOICE_ID          BIGINT references invoices(id),
    USER_ID             BIGINT references users(id),
    TENANT_PROFILE_ID   BIGINT references TENANT_PROFILES(id),
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP,
    DELETED_AT          TIMESTAMP
);